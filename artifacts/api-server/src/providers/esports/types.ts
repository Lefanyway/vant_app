export type GameId = "valorant" | "cs2" | "lol";
export type MatchStatus = "scheduled" | "live" | "finished" | "cancelled" | "postponed";
export type ExternalId = { provider: string; id: string };
export type Game = { id: GameId; name: string; shortName: string; logoUrl?: string };
export type Team = { id: string; externalIds: ExternalId[]; name: string; acronym?: string; logoUrl?: string; country?: string; gameId: GameId };
export type TeamPlayer = { id: string; name: string; fullName?: string; imageUrl?: string; country?: string; role?: string; status?: "player" | "coach" | "staff" };
export type TeamDetails = Team & { website?: string; socials?: { platform: string; url: string }[]; roster?: TeamPlayer[] };
export type TeamMatchFilter = "all" | "upcoming" | "finished";
export type TeamStats = {
  period: "30d";
  matches: number;
  wins: number;
  losses: number;
  mapsPlayed?: number;
  mapsWon?: number;
  averageRoundsWon?: number;
  mapWinRate?: number;
};
export type TeamNewsArticle = {
  id: string;
  title: string;
  url: string;
  publishedAt: string;
  source: string;
  imageUrl?: string;
  summary?: string;
};
export type TeamPageCapabilities = { overview: true; matches: boolean; roster: boolean; stats: boolean; news: boolean };
export type TeamOverview = {
  team: TeamDetails;
  nextMatch: Match | null;
  recentMatches: Match[];
  competitions: Competition[];
  rosterPreview: TeamPlayer[];
  recentForm: ("W" | "L" | "D")[];
  capabilities: TeamPageCapabilities;
};
export type Competition = { id: string; externalIds: ExternalId[]; name: string; slug?: string; logoUrl?: string; region?: string; serieName?: string; gameId: GameId };
export type Stream = { url: string; language?: string; official?: boolean };
export type Match = {
  id: string; externalIds: ExternalId[]; gameId: GameId; competition: Competition;
  homeTeam: Team; awayTeam: Team; startTime: string; status: MatchStatus; bestOf?: 1 | 3 | 5;
  homeScore?: number; awayScore?: number; streams?: Stream[];
};
export type MatchDetails = {
  match: Match;
  maps: { id: string; mapName?: string; mapNumber: number; homeScore?: number; awayScore?: number }[];
  playerStats: unknown[];
  economy: null;
  veto: null;
  headToHead: Match[];
  recentMatches: { teamId: string; matches: Match[] }[];
  capabilities: { maps: boolean; playerStats: boolean; economy: boolean; veto: boolean; headToHead: boolean; recentMatches: boolean };
};
export type ValorantMatchLookup = { homeTeam: Team; awayTeam: Team; startTime: string; competition?: Competition; bestOf?: 1 | 3 | 5 };
export type ValorantProviderMatch = { providerMatchId: string; homeTeamName: string; awayTeamName: string; startTime: string; competitionName?: string; bestOf?: 1 | 3 | 5 };
export type ValorantMapStats = { id: string; mapName: string; mapNumber: number; homeScore?: number; awayScore?: number; status?: "scheduled" | "live" | "finished" };
export type ValorantPlayerStats = { playerId: string; playerName: string; teamId?: string; agent?: string; rating?: number; acs?: number; kills?: number; deaths?: number; assists?: number; kast?: number; adr?: number; headshotPercentage?: number; firstKills?: number; firstDeaths?: number };
export type ValorantEconomy = { homeRoundsWon?: number; awayRoundsWon?: number; homePistolRoundsWon?: number; awayPistolRoundsWon?: number; homeAttackRoundsWon?: number; awayAttackRoundsWon?: number; homeDefenseRoundsWon?: number; awayDefenseRoundsWon?: number };
export type ValorantVetoAction = { teamName: string; action: "ban" | "pick" | "remain"; mapName: string };
/** Public stats model. Provider lookup identifiers must stay inside the adapter/route. */
export type VantValorantMatchStats = { maps: ValorantMapStats[]; playerStats: ValorantPlayerStats[]; economy?: ValorantEconomy; veto: ValorantVetoAction[]; headToHead: Match[]; recentMatches: { teamId: string; matches: Match[] }[] };
export type ValorantStatsCapabilities = { deepStats: boolean; maps: boolean; playerStats: boolean; economy: boolean; veto: boolean; headToHead: boolean; recentMatches: boolean };
export type ValorantStatsResult = { stats: VantValorantMatchStats | null; capabilities: ValorantStatsCapabilities; error?: "VLR enrichment unavailable" | "VLR match not found" };
export type ValorantStatsProvider = {
  name: string;
  findMatch(input: ValorantMatchLookup): Promise<ValorantProviderMatch | null>;
  getMatchStats(providerMatchId: string): Promise<VantValorantMatchStats | null>;
  getHeadToHead(input: { homeTeam: Team; awayTeam: Team }): Promise<Match[]>;
  getRecentMatches(team: Team, limit?: number): Promise<Match[]>;
};
export type MatchQuery = { game?: GameId; date?: string; from?: string; to?: string; timezone?: string };
export type SearchResult = { type: "team" | "competition" | "game"; id: string; name: string; gameId?: GameId; logoUrl?: string };
export type ProviderCapabilities = { schedules: boolean; results: boolean; runningMatches: boolean; historicalStats: boolean; liveTelemetry: boolean };
export type EsportsDataProvider = {
  name: string;
  capabilities: Record<GameId, ProviderCapabilities>;
  getGames(): Promise<Game[]>;
  getMatches(query?: MatchQuery): Promise<Match[]>;
  getLiveMatches(game?: GameId): Promise<Match[]>;
  getUpcomingMatches(game?: GameId): Promise<Match[]>;
  getPastMatches(game?: GameId): Promise<Match[]>;
  getMatch(id: string): Promise<Match | null>;
  getMatchDetails?(id: string): Promise<MatchDetails | null>;
  getCompetitions(game?: GameId): Promise<Competition[]>;
  getCompetition(id: string): Promise<Competition | null>;
  getTeams(game?: GameId): Promise<Team[]>;
  getTeam(id: string): Promise<Team | null>;
  getTeamDetails?(id: string): Promise<TeamDetails | null>;
  getTeamMatches?(id: string, filter: TeamMatchFilter, page?: number, perPage?: number): Promise<{ matches: Match[]; hasMore: boolean }>;
  getTeamStats?(id: string, period?: "30d"): Promise<TeamStats | null>;
  getTeamNews?(id: string, limit?: number): Promise<TeamNewsArticle[]>;
  search(query: string): Promise<SearchResult[]>;
};
